import { existsSync, readFileSync, writeFileSync } from "node:fs";

const manifest = JSON.parse(readFileSync(new URL("../images-speed/provenance.json", import.meta.url), "utf8"));
const heavyFile = new URL("../images-heavy/provenance.json", import.meta.url);
if (existsSync(heavyFile)) {
  const heavy = JSON.parse(readFileSync(heavyFile, "utf8"));
  const bySource = new Map(heavy.photos.map(photo => [photo.sourceId, photo]));
  manifest.photos = manifest.photos.map(photo => bySource.get(photo.sourceId) || photo);
}
const assets = Object.fromEntries(manifest.photos.map(photo => [photo.sourceId, photo]));
const output = `// Generated by scripts/export-speed-photos.mjs from images-speed/provenance.json.\nexport const speedPhotoAssets = ${JSON.stringify(assets, null, 2)};\nexport const speedPhotoRoutes = ${JSON.stringify(manifest.routes, null, 2)};\n`;
const file = new URL("../speed/photo-catalog.js", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(file, "utf8").replaceAll("\r\n", "\n") !== output) throw new Error("The speed photographic catalogue is stale.");
} else {
  writeFileSync(new URL("../images-speed/provenance.json", import.meta.url), JSON.stringify(manifest, null, 2) + "\n");
  writeFileSync(file, output);
  const ledgerFile = new URL("../IMAGE-ATTRIBUTION.csv", import.meta.url);
  const ledger = readFileSync(ledgerFile, "utf8").replace(/^\uFEFF/, "").trimEnd().split(/\r?\n/)
    .filter(line => !line.startsWith('"images-speed/') && !line.startsWith('"images-heavy/'));
  const quote = value => `"${String(value).replaceAll('"', '""')}"`;
  const rows = manifest.photos.filter(photo => photo.sourceId.startsWith("pexels:") || photo.file.startsWith("images-heavy/")).map(photo => [
    photo.file, "image derivative", photo.title, photo.photographer, photo.license, photo.source,
    `${photo.processing || "Optimized website photograph"}; photographer: ${photo.photographerUrl}; processing, dimensions and SHA256: images-speed/provenance.json; license: ${photo.licenseUrl}`,
  ].map(quote).join(","));
  writeFileSync(ledgerFile, [...ledger, ...rows].join("\n") + "\n");
}
console.log(`${Object.keys(assets).length} distinct photographic sources recorded for ${Object.keys(manifest.routes).length} speed pages.`);
