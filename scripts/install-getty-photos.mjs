import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { candidates, replacementFor } from "./getty-photo-plan.mjs";
import { photoAudit } from "./export-photo-audit.mjs";

const metadataPath = process.argv[2];
if (!metadataPath) throw new Error("Supply the independently generated original/derivative metadata JSON.");
const files = JSON.parse(readFileSync(metadataPath, "utf8").replace(/^\uFEFF/, ""));
const provenanceUrl = new URL("../images-getty/provenance.json", import.meta.url);
const provenance = JSON.parse(readFileSync(provenanceUrl, "utf8"));
const audit = await photoAudit();
const paths = audit.audit.replace(/^\uFEFF/, "").trim().split(/\r?\n/).slice(1)
  .map(line => line.match(/^"([^"]+)"/)[1]);
const existing = provenance.assets.filter(asset => !candidates.some(candidate => candidate.id === asset.id));
const medium = new Set(["1321502100", "183319682", "894870474"]);
for (const candidate of candidates) {
  const file = files.find(file => file.id === candidate.id);
  if (!file) throw new Error(`No independently verified derivative for ${candidate.id}`);
  const bytes = readFileSync(new URL(`../${file.file}`, import.meta.url));
  if (createHash("sha256").update(bytes).digest("hex") !== file.sha256) {
    throw new Error(`Derivative changed after processing: ${candidate.id}`);
  }
}
const newAssets = candidates.map(candidate => ({
  id: candidate.id, title: candidate.title, source: candidate.source,
  credit: `${candidate.credit} / Getty Images`, collection: candidate.collection,
  licenseType: "Royalty-free", assetFamily: "Creative", releaseInfo: candidate.releaseInfo,
  ...files.find(file => file.id === candidate.id),
  download: {
    observedOn: "2026-10-24", selectedSize: medium.has(candidate.id) ? "Medium" : "Large",
    evidence: "Immediately before the normal DOWNLOAD: PREMIUM ACCESS; Content available with your current agreements; matching Creative ID; Royalty-free; no editorial-only notice, purchase, visible credit charge or new terms. Download completed in the user-authenticated dedicated Edge profile.",
  },
  placement: paths.filter(path => replacementFor(path) === candidate.id).join("; "),
}));
provenance.assets = [...existing, ...newAssets];
provenance.scope = "All thirty properties: complete active-photo Getty replacement, local review only; no deployment authorized";
provenance.downloadEvidence = "Six earlier downloads plus 69 new normal authenticated downloads under observed existing agreement access. Each detail page was checked immediately before DOWNLOAD for exact Creative ID, Royalty-free and no editorial-only notice. No purchase, visible credit charge or new-terms action was taken. New assets 1321502100, 183319682 and 894870474 used Medium, their highest offered size; the other 66 new assets used Large. Earlier asset 1315418850 also used Medium.";
provenance.processing = "Web JPEG derivatives: high-quality bicubic, quality 85, preserved aspect ratio. Earlier six are 1600px wide; 69 new assets have a maximum edge of 1600px. Source dimensions, byte lengths and SHA256 hashes independently read from downloaded original files; originals remain outside Git. Contributor credits retained separately.";
writeFileSync(provenanceUrl, JSON.stringify(provenance, null, 2) + "\n");
const byId = Object.fromEntries(provenance.assets.map(asset => [asset.id, {
  id: asset.id, title: asset.title, file: asset.file, credit: `Photo by ${asset.credit}`,
  note: "Illustrative Getty stock reference; not the fictional provider, its premises, staff or customers. Not a current service, condition or access guarantee.",
}]));
const replacements = Object.fromEntries(paths.map(path => [path, replacementFor(path)]));
const catalog = `// Generated by scripts/install-getty-photos.mjs from verified provenance and the photo audit.\nexport const gettyPhotos = ${JSON.stringify(byId, null, 2)};\nexport const gettyPhotoReplacements = ${JSON.stringify(replacements, null, 2)};\nexport const replacedPhotoUsage = ${JSON.stringify(audit.sources, null, 2)};\n`;
writeFileSync(new URL("../sites/getty-photo-catalog.js", import.meta.url), catalog);

const csvUrl = new URL("../IMAGE-ATTRIBUTION.csv", import.meta.url);
const legacyUrl = new URL("../IMAGE-ATTRIBUTION-LEGACY.csv", import.meta.url);
if (!existsSync(legacyUrl)) writeFileSync(legacyUrl, readFileSync(csvUrl));
const legacy = readFileSync(legacyUrl, "utf8");
const videoRows = legacy.split(/\r?\n/).filter(line => /^"[^"]+","video",/.test(line));
const csv = value => `"${String(value).replaceAll('"', '""')}"`;
const attributionRows = provenance.assets.map(asset => [
  asset.file, "image", asset.title, asset.credit, "Getty Images Royalty-free; existing agreement access observed",
  asset.source, `${asset.credit}; Creative #${asset.id}. Contextual stock, not actual sample businesses or current conditions. Download and original/derivative hashes: images-getty/provenance.json.`,
].map(csv).join(","));
writeFileSync(csvUrl, ["File,Type,Title,Creator,License,Source URL,Attribution", ...attributionRows, ...videoRows, ""].join("\r\n"));
const md = ["# Active image attribution", "",
  "All active website photographs are local Getty derivatives. Every still was individually checked as Creative, Royalty-free and not editorial-only before the normal existing-agreement download. RF is not public domain. Stock photographs do not verify fictional businesses, people, accessibility, services or current conditions.",
  "", "Originals remain outside the repository. Full source/derivative dimensions, sizes, hashes and download evidence: `images-getty/provenance.json`. The previous Pexels/Wikimedia ledger is preserved only in `IMAGE-ATTRIBUTION-LEGACY.csv`; historical photo thumbnails are no longer presented on the website.", "",
  ...provenance.assets.map(asset => `- \`${asset.file}\` — ${asset.title}. ${asset.credit}. Creative #${asset.id}; Royalty-free. ${asset.source}`),
  "", "## Video records", "",
  "The owner-supplied Getty watch source/playback is unchanged. Earlier videos remain recorded for traceability.", "",
  ...videoRows.map(line => {
    const row = [...line.matchAll(/"((?:[^"]|"")*)"(?:,|$)/g)].map(match => match[1].replaceAll('""', '"'));
    return `- \`${row[0]}\` — ${row[2]}. ${row[3]}. ${row[4]}. ${row[5]}\n  ${row[6]}`;
  }), ""];
writeFileSync(new URL("../IMAGE-ATTRIBUTION.md", import.meta.url), md.join("\n"));
console.log(`Installed ${newAssets.length} newly verified derivatives; ${provenance.assets.length} Getty stills in total.`);
